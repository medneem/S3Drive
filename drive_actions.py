"""Windows disk readiness, desktop shortcut and post-mount operations."""
from __future__ import annotations

import os
import re
from enum import Enum
from pathlib import Path


class MountState(Enum):
    WAITING = "waiting"
    READY = "ready"
    FAILED = "failed"
    TIMED_OUT = "timed_out"


def mount_state(*, process_alive: bool, drive_ready: bool,
                elapsed_seconds: float, timeout_seconds: float = 40) -> MountState:
    """Never report success just because the rclone process started."""
    if not process_alive:
        return MountState.FAILED
    if drive_ready:
        return MountState.READY
    if elapsed_seconds >= timeout_seconds:
        return MountState.TIMED_OUT
    return MountState.WAITING


def disk_root(drive: str) -> str:
    if not re.fullmatch(r"[A-Z]:", drive):
        raise ValueError("Некорректная буква диска.")
    return drive + "\\"


def create_desktop_shortcut(drive: str, name: str, shell=None) -> tuple[Path, bool]:
    """Create a profile-named desktop shortcut; migrate only S3Drive-owned ones.

    The drive root and S3Drive description must both match before an existing
    shortcut can be modified or removed. Never overwrite unrelated .lnk files.
    """
    root = disk_root(drive)
    if not name.strip():
        raise ValueError("Название подключения не может быть пустым.")
    # A profile label may contain symbols that Windows forbids in filenames.
    safe_name = re.sub(r'[<>:"/\\|?*\x00-\x1f]', "_", name).strip().rstrip(". ") or "S3Drive"
    if shell is None:
        if os.name != "nt":
            raise OSError("Ярлыки поддерживаются только в Windows.")
        from win32com.client import Dispatch
        shell = Dispatch("WScript.Shell")
    desktop = Path(shell.SpecialFolders("Desktop"))
    destination = desktop / f"{safe_name} ({drive[0]}).lnk"
    legacy_description = f"Диск S3Drive {drive}"
    description = f"{legacy_description}: {name}"

    def owned(path: Path) -> bool:
        if path.is_symlink():
            return False
        try:
            shortcut = shell.CreateShortcut(str(path))
            target = str(shortcut.TargetPath).rstrip("\\/").casefold()
            desc = str(shortcut.Description)
            return (target == drive.casefold() and
                    (desc == legacy_description or desc.startswith(legacy_description + ": ")))
        except Exception:
            # Broken/foreign shortcuts belong to the user, not to S3Drive.
            return False

    if destination.exists() or destination.is_symlink():
        if not owned(destination):
            raise FileExistsError(f"Ярлык «{destination.name}» уже существует и не принадлежит S3Drive.")
        shortcut = shell.CreateShortcut(str(destination))
        if shortcut.Description != description:
            shortcut.Description = description
            shortcut.Save()
        created = False
    else:
        shortcut = shell.CreateShortcut(str(destination))
        shortcut.TargetPath = root
        shortcut.Description = description
        shortcut.Save()
        created = True

    # Create or confirm the replacement first; only then remove outdated links
    # generated by this app for the same drive letter (including legacy names).
    for candidate in desktop.glob("*.lnk"):
        if candidate != destination and owned(candidate):
            candidate.unlink()
    return destination, created


def open_mounted_disk(drive: str, startfile=None) -> None:
    """Open the mounted root in Windows Explorer."""
    if startfile is None:
        if os.name != "nt":
            raise OSError("Открытие диска поддерживается только в Windows.")
        startfile = os.startfile
    startfile(disk_root(drive))
