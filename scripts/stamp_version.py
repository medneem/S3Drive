"""Stamp a development build or an explicitly approved semantic release.

Usage: python scripts/stamp_version.py 1.0.0 42 [RELEASE_VERSION]
Empty RELEASE_VERSION creates 1.0.0-dev.42; "1.0.0" creates a stable release.
Writes version.py and PyInstaller's Windows VERSIONINFO resource file.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

_SEMVER = re.compile(r"(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)")
_STAMPED = re.compile(r"(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-dev\.([1-9]\d*))?")


def _components(version: str) -> tuple[int, int, int, int]:
    match = _STAMPED.fullmatch(version)
    if match is None:
        raise ValueError("Version must be MAJOR.MINOR.PATCH or MAJOR.MINOR.PATCH-dev.BUILD")
    values = tuple(int(part) if part else 0 for part in match.groups())
    if any(number > 65535 for number in values):
        raise ValueError("Windows executable version components must be <= 65535")
    return values


def make_version(base_version: str, run_number: str, release_version: str = "") -> str:
    if _SEMVER.fullmatch(base_version) is None:
        raise ValueError("BASE_VERSION must look like 1.0.0")
    _components(base_version)

    if not re.fullmatch(r"[1-9]\d*", run_number):
        raise ValueError("GitHub run number must be a positive integer")
    if int(run_number) > 65535:
        raise ValueError("GitHub run number exceeds the Windows version component limit (65535)")

    if release_version:
        release = _SEMVER.fullmatch(release_version)
        if release is None or int(release.group(1)) < 1:
            raise ValueError("Release version must be MAJOR.MINOR.PATCH, starting at 1.0.0 (without v)")
        _components(release_version)
        return release_version

    return f"{base_version}-dev.{int(run_number)}"


def windows_version_info(version: str) -> str:
    numeric = _components(version)
    file_version = ".".join(str(part) for part in numeric)
    return f"""VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={numeric!r},
    prodvers={numeric!r},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', 'medneem'),
        StringStruct('FileDescription', 'S3Drive'),
        StringStruct('FileVersion', '{file_version}'),
        StringStruct('InternalName', 'S3Drive'),
        StringStruct('OriginalFilename', 'S3Drive.exe'),
        StringStruct('ProductName', 'S3Drive'),
        StringStruct('ProductVersion', '{version}')
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def stamp_version(
    base_version: str, run_number: str, project_root: Path, release_version: str = ""
) -> str:
    version = make_version(base_version, run_number, release_version)
    (project_root / "version.py").write_text(
        '"""Build version, generated by CI."""\n'
        f'APP_VERSION = "{version}"\n',
        encoding="utf-8",
    )
    (project_root / "windows_version_info.txt").write_text(
        windows_version_info(version), encoding="utf-8"
    )
    return version


if __name__ == "__main__":
    if len(sys.argv) not in (3, 4):
        print("Usage: stamp_version.py BASE_VERSION RUN_NUMBER [RELEASE_VERSION]", file=sys.stderr)
        raise SystemExit(2)
    root = Path(__file__).resolve().parent.parent
    requested_release = sys.argv[3] if len(sys.argv) == 4 else ""
    try:
        created = stamp_version(sys.argv[1], sys.argv[2], root, requested_release)
    except ValueError as exc:
        print(f"Build version error: {exc}", file=sys.stderr)
        raise SystemExit(2) from exc
    print(f"Generated application version {created}")
